    slide = prs.slides.add_slide(prs.slide_layouts[6])
    bg = slide.shapes.add_shape(MSO_SHAPE.RECTANGLE, Inches(0), Inches(0), Inches(13.333), Inches(7.5))
    set_fill(bg, COLORS["pale"])
    set_line(bg)

    add_header(slide, page_no, item["title"])
    add_core_bar(slide, item["core"])
    add_card(slide, "页面正文", item["body"], 0.48, 1.73, 7.62, 4.95, COLORS["blue"], body_size=8.8)
    add_card(slide, "画面/图片建议", item["image"], 8.34, 1.73, 4.5, 1.5, COLORS["green"], body_size=7.4)
    add_card(slide, "现场布置或物料建议", item["materials"], 8.34, 3.45, 4.5, 1.5, COLORS["orange"], body_size=7.4)
    add_card(slide, "执行说明", item["execution"], 8.34, 5.17, 4.5, 1.5, COLORS["blue"], body_size=7.4)
    add_decor(slide, page_no)


